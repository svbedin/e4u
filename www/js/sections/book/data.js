/** One sentence: the text before and after the gap, the right answer, the wrong ones and the whole sentence. */
export function parseGap(s) {
  const m = s.match(/^(.*?)\{([^}]+)\}(.*)$/);
  const [a, ...w] = m[2].split('|');
  const before = m[1], after = m[3].replace(/^ (?=[.,!?])/, '');
  return { before, after, a, w, full: (before + a + after).replace(/\s+/g, ' ').trim() };
}
